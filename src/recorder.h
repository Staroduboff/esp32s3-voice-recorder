// =====================================================================================
// recorder.h — microSD-карта и запись WAV-файлов
// =====================================================================================
// Карта подключена по SPI и должна быть отформатирована в FAT32 (карты до 32 ГБ так и
// продаются). Записи — файлы REC_0001.WAV, REC_0002.WAV, … в корне карты: для новой записи
// берётся первый свободный номер. Даты у файлов будут 1980 года, потому что часов на плате нет.
//
// Как устроен WAV
// ---------------
// WAV-файл — это 44 байта заголовка (частота дискретизации, разрядность, число каналов,
// длина звука), а за ними все 16-битные отсчёты подряд. Длина звука заранее неизвестна,
// поэтому заголовок сначала пишется с нулевой длиной и исправляется при остановке.
// Чтобы файл оставался читаемым и при внезапной потере питания, раз в CHECKPOINT_MS
// заголовок обновляется, а данные сбрасываются на карту (recorderTick).
//
// Почему запись идёт через буфер
// ------------------------------
// Отсчёты копятся в буфере на 8 КБ (0,25 с звука) и уходят на карту одним куском.
// SD-карты пишут данные блоками по 512 байт, и крупные куски, кратные 512, они пишут
// намного быстрее, чем много мелких.
//
// Как пользоваться
// ----------------
//   setup():  sdBegin();
//   запись:   recorderStart();  затем в каждом цикле  recorderWrite(отсчёты, n); recorderTick();
//   стоп:     recorderStop();
// =====================================================================================
#pragma once

#include <Arduino.h>

// Подключить и смонтировать карту. false — карты нет, она не в FAT32 или не отвечает.
bool sdBegin();

// Описание карты на момент включения: объём, свободное место, частота шины. Для логов.
const char *sdInfo();

// Создать новый файл REC_xxxx.WAV и начать запись. false — не удалось создать файл.
bool recorderStart();

// Дописать count отсчётов. false — ошибка записи на карту (карту вынули, она сбоит).
bool recorderWrite(const int16_t *samples, size_t count);

// Вызывать в каждом цикле во время записи: раз в CHECKPOINT_MS сбрасывает данные на карту
void recorderTick();

// Дописать остаток буфера, исправить заголовок и закрыть файл
void recorderStop();
