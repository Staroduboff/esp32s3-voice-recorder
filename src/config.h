// =====================================================================================
// config.h — все настройки диктофона в одном месте
// =====================================================================================
// Здесь собраны номера пинов и параметры, которые может понадобиться поменять.
// Остальные файлы берут значения отсюда: например, если перепаять провод на другой пин,
// достаточно исправить одну строку в этом файле.
//
// Схема подключения — wiring.svg / wiring.jpg в корне проекта.
// =====================================================================================
#pragma once

#include <Arduino.h>
#include "driver/gpio.h"

// ---------------------------------------------------------------------------------------
// Пины ESP32-S3-Zero
// Числа — номера GPIO, они же напечатаны на плате рядом с отверстиями («4» = GPIO4).
// ---------------------------------------------------------------------------------------

// Кнопка BOOT на самой плате. При нажатии замыкает пин на землю, поэтому читается как LOW.
// GPIO0 — strapping-пин: если держать BOOT в момент включения или нажатия RESET, ESP32
// запустится не в программу, а в режим прошивки. После загрузки это обычная кнопка.
constexpr gpio_num_t PIN_BUTTON = GPIO_NUM_0;

// Адресный RGB-светодиод WS2812 на плате. Цвет задаётся по одному проводу функцией rgbLedWrite().
constexpr uint8_t PIN_LED = 21;

// Микрофон INMP441 — цифровой, отдаёт звук по шине I2S (подробно в mic.h)
constexpr gpio_num_t PIN_MIC_SCK = GPIO_NUM_4;  // SCK: такты отдельных битов, их выдаёт ESP32
constexpr gpio_num_t PIN_MIC_WS = GPIO_NUM_5;   // WS: такт «левый/правый канал» = частота дискретизации
constexpr gpio_num_t PIN_MIC_SD = GPIO_NUM_6;   // SD: данные от микрофона (Serial Data, это не SD-карта!)

// microSD-модуль, шина SPI. GPIO10–13 — штатные пины SPI2 у ESP32-S3: на них SPI подключается
// к выводам напрямую, без коммутатора GPIO, и может работать на больших частотах.
constexpr int PIN_SD_CS = 10;    // CS: выбор устройства на шине
constexpr int PIN_SD_MOSI = 11;  // MOSI: данные ESP32 → карта
constexpr int PIN_SD_CLK = 12;   // CLK: такты
constexpr int PIN_SD_MISO = 13;  // MISO: данные карта → ESP32

// ---------------------------------------------------------------------------------------
// Звук
// ---------------------------------------------------------------------------------------

// Частота дискретизации, отсчётов в секунду. Для речи 16 кГц достаточно (в телефоне 8 кГц),
// большинство систем распознавания речи ждут именно 16 кГц. Минута записи = 1,9 МБ.
constexpr uint32_t SAMPLE_RATE = 16000;

// Частота среза фильтра высоких частот (ФВЧ). Модуль INMP441 из набора выдаёт постоянное
// смещение и сильный «гул» ниже 40 Гц. Без фильтра после усиления это перегрузка и шумная
// тишина. Фильтр на 80 Гц убирает их, а речь (основная энергия выше ~100 Гц) почти не трогает.
constexpr float HIGHPASS_HZ = 80.0f;

// Усиление при переводе в 16 бит: 1 — как есть, 8 — +18 дБ (подобрано для речи с 0,5–1 м).
// Если громкая речь вблизи хрипит, значит, сигнал упирается в предел 16 бит: уменьшить.
// Если запись слишком тихая — увеличить.
constexpr float GAIN = 8.0f;

// ---------------------------------------------------------------------------------------
// SD-карта
// ---------------------------------------------------------------------------------------

// Частота шины SPI. 20 МГц проверены на макете: запись около 1,2 МБ/с при нужных для звука
// 32 КБ/с. Если карта на 20 МГц не заведётся (длинные провода, плохой контакт),
// прошивка попробует запасную частоту 4 МГц — для звука хватит и её.
constexpr uint32_t SD_SPI_HZ = 20000000;
constexpr uint32_t SD_SPI_HZ_SLOW = 4000000;

// Как часто во время записи обновлять заголовок WAV и сбрасывать данные на карту, мс.
// Если питание пропадёт посреди записи, файл останется целым, потеряются последние секунды.
constexpr uint32_t CHECKPOINT_MS = 10000;

// ---------------------------------------------------------------------------------------
// Кнопка
// ---------------------------------------------------------------------------------------

// Контакты кнопки при нажатии несколько миллисекунд «дребезжат» (быстро замыкаются и размыкаются).
// Состояние считается изменившимся, только если оно продержалось столько миллисекунд.
constexpr uint32_t DEBOUNCE_MS = 30;

// Сколько держать кнопку, чтобы это считалось долгим нажатием (режим USB-флешки), мс
constexpr uint32_t LONG_PRESS_MS = 2000;
