// =====================================================================================
// mic.h — цифровой микрофон INMP441
// =====================================================================================
// Как это работает
// ----------------
// INMP441 сам оцифровывает звук и передаёт готовые числа по шине I2S. На шине три провода:
//   SCK — такты битов. Их выдаёт ESP32 (она «ведущий»): 16 000 × 64 = 1,024 МГц;
//   WS  — такт каналов: половина периода «левый канал», половина «правый», частота 16 кГц;
//   SD  — данные: на каждый такт SCK микрофон выдаёт один бит отсчёта.
// Отсчёт — 24-битное число со знаком, мгновенное давление звука. Пин L/R микрофона замкнут
// на GND, поэтому микрофон «говорит» только в левой половине периода WS, а в правой молчит.
//
// Принимает биты аппаратный блок I2S внутри ESP32. Через DMA (прямой доступ к памяти)
// он складывает отсчёты в кольцо буферов без участия процессора. Программа забирает
// готовые буферы функцией micRead(). Если долго не забирать (например, пока SD-карта
// записывает данные), кольцо переполнится и кусок звука потеряется — такие потери
// считает micLostBuffers().
//
// Перед выдачей каждый отсчёт проходит фильтр высоких частот и усиление (настройки
// в config.h) и превращается в обычный 16-битный отсчёт, как в WAV-файле.
//
// Как пользоваться
// ----------------
//   setup():  micBegin();
//   loop():   int16_t chunk[MIC_CHUNK_SAMPLES];
//             size_t n = micRead(chunk);   // n свежих отсчётов, обычно 480 = 30 мс звука
// =====================================================================================
#pragma once

#include <Arduino.h>

// Сколько отсчётов отдаёт micRead() за один вызов: 480 отсчётов = 30 мс звука при 16 кГц.
// Это же размер одного DMA-буфера.
constexpr size_t MIC_CHUNK_SAMPLES = 480;

// Запустить шину I2S и микрофон. Вызвать один раз в setup().
// Возвращает false, если драйвер I2S не запустился (ошибка в настройках, а не в пайке:
// оборванный провод драйвер не заметит, запись просто будет тихой).
bool micBegin();

// Забрать очередную порцию звука в массив out (на MIC_CHUNK_SAMPLES отсчётов).
// Если свежих данных ещё нет, ждёт их (до ~30 мс). Возвращает число отсчётов, 0 — ошибка.
size_t micRead(int16_t (&out)[MIC_CHUNK_SAMPLES]);

// Сколько DMA-буферов (по 30 мс) потеряно с момента включения: программа не успела их забрать
uint32_t micLostBuffers();
