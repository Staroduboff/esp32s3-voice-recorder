// =====================================================================================
// usb_drive.h — режим «USB-флешка»: SD-карта видна компьютеру как накопитель
// =====================================================================================
// Зачем
// -----
// Чтобы забирать записи без кардридера: плата подключена к компьютеру по USB, долгое
// нажатие BOOT — и в «Этом компьютере» появляется диск с файлами REC_xxxx.WAV.
//
// Как это работает
// ----------------
// У ESP32-S3 есть полноценный USB-контроллер (USB-OTG). Прошивка собрана в режиме OTG
// (ARDUINO_USB_MODE=0 в platformio.ini), и компьютер видит плату сразу как два устройства:
// COM-порт (Serial, логи) и USB-накопитель (Mass Storage). Пока режим флешки выключен,
// накопитель «без носителя», как кардридер без карты.
//
// После usbDriveEnable() компьютер получает прямой доступ к секторам карты (по 512 байт)
// и сам разбирает на ней FAT32 — как с обычной флешкой. Сама прошивка в это время
// карту не трогает: если файлы будут менять и ESP32, и компьютер, файловая система
// испортится. Поэтому выход из режима — только перезагрузкой платы: при старте карта
// монтируется заново и видит всё, что на ней поменял компьютер.
// =====================================================================================
#pragma once

// Подготовить накопитель. Вызвать один раз после успешного sdBegin().
void usbDriveSetup();

// Отдать карту компьютеру. Перед этим запись должна быть остановлена.
void usbDriveEnable();

// Забрать карту у компьютера (он увидит, что носитель вынули)
void usbDriveDisable();

// true, если в Windows нажали «Извлечь» для этого диска
bool usbDriveEjected();
